// Generates src/schema.sql from docs/project/db_design.md (single source of truth for the DB).
import { readFileSync, writeFileSync } from 'node:fs';
const md = readFileSync(new URL('../../docs/project/db_design.md', import.meta.url), 'utf8');
const NOW = "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))";
const tables = [];
for (const sec of md.split(/\n### /).slice(1)) {
  const lines = sec.split('\n');
  const name = lines[0].trim();
  const cols = [];
  for (const l of lines) {
    if (!l.startsWith('|') || l.startsWith('| Column') || l.startsWith('|---')) continue;
    const c = l.trim().replace(/^\||\|$/g, '').split('|').map((x) => x.trim());
    cols.push({ name: c[0], type: c[1], nullable: c[2] === 'Y', def: c[3], key: c[4], index: c[5], cons: c[6] });
  }
  tables.push({ name, cols });
}
const out = ['-- GENERATED by scripts/gen-schema.mjs from docs/project/db_design.md. Do not edit by hand.', 'PRAGMA foreign_keys = ON;', ''];
const post = [];
const q = (v) => (/^-?\d+(\.\d+)?$/.test(v) ? v : `'${v.replace(/'/g, "''")}'`);
for (const t of tables) {
  const names = new Set(t.cols.map((c) => c.name));
  const pks = t.cols.filter((c) => /(^|, )PK/.test(c.key));
  const defs = [], checks = [];
  for (const c of t.cols) {
    let d = `  ${c.name} ${c.type}`;
    if (pks.length === 1 && pks[0] === c) d += ' PRIMARY KEY';
    if (!c.nullable) d += ' NOT NULL';
    if (c.def === 'now') d += ` DEFAULT ${NOW}`;
    else if (c.def && c.def !== 'NULL') d += ` DEFAULT ${c.def}`;
    const fk = c.key.match(/FK -> (\w+)\.(\w+)/);
    const parts = c.cons.split(';').map((x) => x.trim()).filter(Boolean);
    if (/(^|, )UQ$/.test(c.key) || parts.includes('UQ') || parts.some((p) => /^UQ \((?![a-z_]+(, [a-z_]+)*\))/.test(p))) d += ' UNIQUE';
    if (fk) {
      d += ` REFERENCES ${fk[1]}(${fk[2]})`;
      if (parts.includes('on delete cascade')) d += ' ON DELETE CASCADE';
      else if (parts.includes('on delete set null')) d += ' ON DELETE SET NULL';
    }
    const n = c.nullable ? `${c.name} IS NULL OR ` : '';
    for (const p of parts) {
      let m;
      if ((m = p.match(/^in \((.*)\)$/))) { const vs = m[1].split(',').map((x) => x.trim()); checks.push(`${n}${c.name} IN (${vs.map(q).join(', ')})`); }
      else if (p.startsWith('0/1')) checks.push(`${n}${c.name} IN (0, 1)`);
      else if (c.type !== 'TEXT' && (m = p.match(/^(-?\d+(?:\.\d+)?)-(-?\d+(?:\.\d+)?)$/))) checks.push(`${n}${c.name} BETWEEN ${m[1]} AND ${m[2]}`);
      else if ((m = p.match(/^(>=|>)\s*(-?\d+(?:\.\d+)?)$/))) checks.push(`${n}${c.name} ${m[1]} ${m[2]}`);
      else if ((m = p.match(/^(>=|>)\s*([a-z_0-9]+)$/)) && names.has(m[2])) checks.push(`${n}${m[2]} IS NULL OR ${c.name} ${m[1]} ${m[2]}`);
      else if (p === 'json_valid') checks.push(`${n}json_valid(${c.name})`);
      else if (p === 'lower-case') checks.push(`${n}${c.name} = lower(${c.name})`);
      else if (p === 'HH:mm') checks.push(`${n}${c.name} GLOB '[0-2][0-9]:[0-5][0-9]'`);
      else if (p === 'date') checks.push(`${n}${c.name} GLOB '[0-9][0-9][0-9][0-9]-[0-1][0-9]-[0-3][0-9]'`);
      else if ((m = p.match(/^UQ \(([a-z_]+(?:, [a-z_]+)*)\)(?: where (.+))?$/))) post.push(`CREATE UNIQUE INDEX IF NOT EXISTS uq_${t.name}_${m[1].replace(/, /g, '_')} ON ${t.name} (${m[1]})${m[2] ? ' WHERE ' + m[2] : ''};`);
    }
    defs.push(d);
    if (c.index && !c.index.startsWith('FTS5')) {
      const cols = c.index.startsWith('(') ? c.index.replace(/\s+where.*/, '').slice(1, -1) : c.name;
      const where = c.index.match(/where (.+)$/);
      const nm = `idx_${t.name}_${cols.replace(/, /g, '_')}${where ? '_p' : ''}`;
      post.push(`CREATE INDEX IF NOT EXISTS ${nm} ON ${t.name} (${cols})${where ? ' WHERE ' + where[1] : ''};`);
    }
    if (c.index.startsWith('FTS5')) post.push(`CREATE VIRTUAL TABLE IF NOT EXISTS ${t.name}_fts USING fts5(title, notes, content='${t.name}', content_rowid='rowid');`,
      `CREATE TRIGGER IF NOT EXISTS ${t.name}_ai AFTER INSERT ON ${t.name} BEGIN INSERT INTO ${t.name}_fts(rowid, title, notes) VALUES (new.rowid, new.title, new.notes); END;`,
      `CREATE TRIGGER IF NOT EXISTS ${t.name}_ad AFTER DELETE ON ${t.name} BEGIN INSERT INTO ${t.name}_fts(${t.name}_fts, rowid, title, notes) VALUES ('delete', old.rowid, old.title, old.notes); END;`,
      `CREATE TRIGGER IF NOT EXISTS ${t.name}_au AFTER UPDATE ON ${t.name} BEGIN INSERT INTO ${t.name}_fts(${t.name}_fts, rowid, title, notes) VALUES ('delete', old.rowid, old.title, old.notes); INSERT INTO ${t.name}_fts(rowid, title, notes) VALUES (new.rowid, new.title, new.notes); END;`);
  }
  if (pks.length > 1) defs.push(`  PRIMARY KEY (${pks.map((c) => c.name).join(', ')})`);
  checks.forEach((c) => defs.push(`  CHECK (${c})`));
  out.push(`CREATE TABLE IF NOT EXISTS ${t.name} (\n${defs.join(',\n')}\n);`, '');
}
out.push(...post, '');
writeFileSync(new URL('../src/schema.sql', import.meta.url), out.join('\n'));
writeFileSync(new URL('../src/tables.json', import.meta.url), JSON.stringify(tables.map((t) => ({ name: t.name, cols: t.cols.map((c) => c.name), pk: t.cols.filter((c) => /(^|, )PK/.test(c.key)).map((c) => c.name), userOwned: t.cols.some((c) => c.name === 'user_id'), editable: t.cols.some((c) => c.name === 'field_versions_json'), fks: t.cols.filter((c) => /FK -> /.test(c.key)).map((c) => ({ col: c.name, ref: c.key.match(/FK -> (\w+)\.(\w+)/)[1] })), appendOnly: !t.cols.some((c) => c.name === 'updated_at'), softDelete: t.cols.some((c) => c.name === 'deleted_at') })), null, 1));
console.log(`${tables.length} tables, ${post.length} indexes/triggers`);
