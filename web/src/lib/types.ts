export type Status = 'planned' | 'in_progress' | 'done' | 'skipped' | 'moved' | 'missed';
export type Priority = 'low' | 'med' | 'high';
export type Energy = 'low' | 'med' | 'high';
export type DayType = 'normal' | 'holiday' | 'exam' | 'rest' | 'day_order';
export type TimerMode = 'free' | 'countdown' | 'sprint' | 'tiny_start';

export interface Category { id: string; name: string; color: string; icon: string; weeklyGoalMin: number }
export interface Subtask { id: string; title: string; done: boolean }

export interface Task {
  id: string;
  title: string;
  notes?: string;
  categoryId: string;
  tags: string[];
  priority: Priority;
  energy: Energy;
  date: string; // YYYY-MM-DD
  start: string; // HH:mm
  dur: number; // minutes
  fixed: boolean;
  top3: boolean;
  goalId?: string;
  source: 'manual' | 'routine' | 'shifted' | 'import' | 'inbox';
  status: Status;
  subtasks: Subtask[];
  spentMin: number; // tracked focus minutes
  doneAt?: number;
  skipReason?: string;
  movedFrom?: string;
  late?: boolean;
  deletedAt?: number;
  routineKey?: string; // `${routineId}:${index}` when generated by a routine
}

export interface InboxItem { id: string; text: string; createdAt: number; archived?: boolean }
export interface Habit { id: string; name: string; icon: string; color: string; cadence: 'daily' | 'weekdays'; target: number; unit: string; paused?: boolean }
export interface HabitLog { habitId: string; date: string; count: number }
export interface Goal { id: string; title: string; categoryId: string; targetType: 'hours' | 'tasks'; targetValue: number; progress: number; due: string }
export interface Routine { id: string; name: string; color: string; icon: string; recurrence: string; categoryId: string; active: boolean; tasks: { title: string; start: string; dur: number }[] }
export interface ClassSlot { id: string; order: number; subject: string; start: string; end: string; room: string; teacher: string }
export interface Attendance { slotId: string; date: string; status: 'attended' | 'absent' | 'cancelled' }
export interface Subject { name: string; color: string; attended: number; total: number; limit: number }

export interface DaySummary { pct: number; done: number; planned: number; min: number; kind?: 'holiday' | 'rest' | 'exam' | 'frozen' }

export interface Change { id: string; before: Partial<Task>; after: Partial<Task> }
export interface ShiftBatch {
  id: string;
  label: string;
  kind: string;
  createdAt: number;
  undoneAt?: number;
  changes: Change[];
  dayTypes: { date: string; from: DayType; to: DayType }[];
  anchor?: { from: { date: string; order: number }; to: { date: string; order: number } };
  counts: { moved: number; skipped: number; overflow: number; fixed: number };
}

export interface HistoryEvent { id: string; at: number; text: string; kind: 'shift' | 'edit' | 'delete' | 'restore' | 'undo' | 'seal' }
export interface Reflection { id: string; period: 'day' | 'week' | 'month'; start: string; text: string; rating: number }

export interface Settings {
  name: string;
  theme: string;
  apexVisual: 'mountain' | 'tree' | 'flame';
  density: 'comfortable' | 'compact';
  dayStartHour: number;
  weekStart: 0 | 1;
  hour12: boolean;
  snap: 5 | 10 | 15 | 30;
  streakThreshold: number; // percent
  freezesPerMonth: number;
  overloadHours: number;
  motion: 'full' | 'reduced';
  sound: boolean;
  tone: 'calm' | 'energetic' | 'tough';
  nudges: boolean;
  nudgeDelay: number;
  nudgeCap: number;
  quietFrom: string;
  quietTo: string;
  notifications: boolean;
  w25: number;
  w50: number;
  planTime: string;
  planDay: number;
  dayEnd: string;
  focusWork: number;
  focusBreak: number;
  tips: boolean;
}
